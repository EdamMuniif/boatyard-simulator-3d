import assert from 'node:assert/strict';
import {PHASES,WAYPOINTS,MISSION,distance2D,canBerthFerry,canAttachSling,canDock} from '../src/rules.js';
assert.equal(PHASES.length,8);
assert.equal(PHASES[0].id,'DISPATCH');
assert.equal(PHASES.at(-1).id,'COMPLETE');
for(const phase of PHASES)assert.ok(WAYPOINTS[phase.id]);
assert.equal(distance2D({x:0,z:0},{x:3,z:4}),5);
assert.equal(canBerthFerry({x:0,z:16},0),true);
assert.equal(canBerthFerry({x:0,z:16},4),false);
assert.equal(canBerthFerry({x:9,z:16},0),false);
assert.equal(canAttachSling({x:0,z:16},0),true);
assert.equal(canAttachSling({x:0,z:16},2),false);
assert.equal(canDock({x:34,z:108},0,MISSION.liftRequired),true);
assert.equal(canDock({x:34,z:108},0,1),false);
assert.equal(canDock({x:34,z:108},2,4),false);
assert.equal(canDock({x:-2,z:108},0,4),false);
assert.ok(MISSION.dockPlacementHeight < MISSION.liftRequired);
assert.ok(MISSION.liftRequired <= MISSION.maxLift);
console.log('PASS: mission and geometry rule checks');
